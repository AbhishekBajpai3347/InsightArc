def _clean_schema(schema: Any) -> Any:
    """Recursively remove redundant 'title' keys generated by Pydantic to minimize token overhead."""
    if isinstance(schema, dict):
        return {k: _clean_schema(v) for k, v in schema.items() if k != "title"}
    if isinstance(schema, list):
        return [_clean_schema(item) for item in schema]
    return schema


# Hard safety limits (rows a tool may receive), checked by the executor BEFORE the tool runs.
# Measured with the unchanged plot functions on this project's setup:
#   bar chart : ~2.9 ms per bar  -> 1,000 bars ~3 s (bars are already narrower than a pixel)
#               (8.3M rows would take hours)
#   scatter   : ~11 us per point -> 1,000,000 points ~11 s, 8.3M ~1.5 min (slow but works,
#               so the limit is set above that: it only stops truly excessive inputs)
# Histogram, box plot and heatmap summarise the data first (8.3M rows < 1 s), so no limit.
MAX_BAR_CHART_ROWS = 1_000
MAX_SCATTER_ROWS = 10_000_000

# Added automatically to the parameters of every tool with accepts_previous_result=True.
SOURCE_PARAMETER = {
    "type": "string",
    "enum": ["dataset", "previous_result"],
    "default": "dataset",
}


@dataclass(frozen=True)
class ToolDefinition:
    name: str
    description: str
    function: Callable
    input_schema: Type[BaseModel] | None = None
    modifies_dataset: bool = False
    # True: the LLM may run this tool on the table produced by an earlier tool
    # (argument source="previous_result") instead of the full dataset.
    accepts_previous_result: bool = False
    # Hard safety limit: the executor refuses inputs with more rows than this (None = no limit).
    max_input_rows: int | None = None

    def get_json_schema(self) -> dict:
        if self.input_schema is None:
            schema = {"type": "object", "properties": {}}
        else:
            schema = _clean_schema(self.input_schema.model_json_schema())
        if self.accepts_previous_result and not self.modifies_dataset:
            schema["properties"]["source"] = SOURCE_PARAMETER
        return schema


