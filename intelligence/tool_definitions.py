def get_llm_tools() -> list[dict]:
    """Convert registered ToolDefinitions to OpenAI / Groq tool specifications."""
    return [
        {
            "type": "function",
            "function": {
                "name": tool.name,
                "description": tool.description,
                "parameters": tool.get_json_schema(),
            },
        }
        for tool in TOOLS.values()
    ]
